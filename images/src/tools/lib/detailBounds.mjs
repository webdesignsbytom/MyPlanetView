// The detailed outlines' bounds (client/src/utils/map/detailShapeBounds.js): where each place's
// land is, so the map fetches and draws a place's detail only when some of it is in view
// (hooks/useDetailedShapes.js). One box per place made far-flung places (the US with Alaska and
// the Aleutians, France with its overseas parts, New Zealand, Kiribati) span most of the map,
// so zooming into Germany fetched the US and Russia (19 Nov 2026, the audit). Each place's
// parts are grouped instead: parts closer than GAP share a box, so a place has a box for each
// stretch of land, a few for most, and the file stays small.

// Parts closer than this (map units, 2000 across) share a box
const GAP = 20;

const round1 = (n) => Math.round(n * 10) / 10;

const boxOf = (pts) => {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const [x, y] of pts) {
    if (x < minX) minX = x;
    if (y < minY) minY = y;
    if (x > maxX) maxX = x;
    if (y > maxY) maxY = y;
  }
  return [minX, minY, maxX, maxY];
};

const near = (a, b) => a[0] - GAP <= b[2] && b[0] - GAP <= a[2] && a[1] - GAP <= b[3] && b[1] - GAP <= a[3];
const join = (a, b) => [Math.min(a[0], b[0]), Math.min(a[1], b[1]), Math.max(a[2], b[2]), Math.max(a[3], b[3])];

/** A place's parts (each an array of [x, y] points) -> its boxes, [[minX, minY, maxX, maxY], …], west to east. */
export function groupedBounds(parts) {
  let boxes = parts.filter((pts) => pts.length).map(boxOf);
  // Join any two near each other until none are (a joined box can reach a third)
  for (let joined = true; joined; ) {
    joined = false;
    for (let i = 0; i < boxes.length && !joined; i++) {
      for (let j = i + 1; j < boxes.length; j++) {
        if (near(boxes[i], boxes[j])) {
          boxes = [...boxes.slice(0, i), join(boxes[i], boxes[j]), ...boxes.slice(i + 1, j), ...boxes.slice(j + 1)];
          joined = true;
          break;
        }
      }
    }
  }
  return boxes.map((box) => box.map(round1)).sort((a, b) => a[0] - b[0] || a[1] - b[1]);
}

/** detailShapeBounds.js's source, from `{ code: parts }`, `generator` naming the tool. */
export function detailBoundsSource(partsByCode, generator) {
  const codes = Object.keys(partsByCode).sort();
  return `// Generated by ${generator}. Don't edit by hand.

// Where each place's detailed outline has land: one box [minX, minY, maxX, maxY] in map units
// per stretch of it (images/src/tools/lib/detailBounds.mjs), so a place's detail is fetched
// only when some of its land is in view (hooks/useDetailedShapes.js; the outlines are in
// detailShapes/)
export const DETAIL_SHAPE_BOUNDS = {
${codes.map((code) => `  ${code}: [${groupedBounds(partsByCode[code]).map((box) => `[${box.join(', ')}]`).join(', ')}],`).join('\n')}
};
`;
}
