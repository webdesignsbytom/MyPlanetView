// The airports a boarding pass or a typed flight can name (23 Nov 2026, the flight log; docs/API.md
// "Flights"): every airport with an IATA code and scheduled flights in OurAirports' list (public
// domain; https://davidmegginson.github.io/ourairports-data/airports.csv), with its place on our
// map found by the server's own lookup (so an airport is in the country the map draws it in: the
// Canaries' in IC, Gatwick in England on a split map), else OurAirports' country.
//
//   node images/src/tools/airports.mjs <airports.csv>          (from the repo root)
//   node images/src/tools/airports.mjs <airports.csv> --check  (fails when the outputs differ)
//
// Writes server/src/data/airports.json and client/src/utils/flights/airportData.js (generated:
// IATA code -> [name, city, place, latitude, longitude, UK nation or null]). Reads no env file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { countryAtPosition } from '../../../server/src/utils/countryLookup.js';
import { ukNationAt } from '../../../server/src/utils/ukNations.js';
import { COUNTRIES } from '../../../client/src/utils/map/countries.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const SERVER_OUT = path.join(ROOT, 'server/src/data/airports.json');
const CLIENT_OUT = path.join(ROOT, 'client/src/utils/flights/airportData.js');
const TYPES = new Set(['large_airport', 'medium_airport', 'small_airport', 'seaplane_base']);
const RANK = { large_airport: 3, medium_airport: 2, small_airport: 1, seaplane_base: 0 };
const KNOWN = new Set(COUNTRIES.map((c) => c.code));

// A CSV line's fields (quoted fields may hold commas and doubled quotes)
function fields(line) {
  const out = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') {
      out.push(field);
      field = '';
    } else field += ch;
  }
  out.push(field);
  return out;
}

const round = (n) => Math.round(n * 10000) / 10000;
const tidy = (text) => text.replace(/\s+/g, ' ').trim();

function build(csvPath) {
  const [header, ...lines] = fs.readFileSync(csvPath, 'utf8').split(/\r?\n/).filter(Boolean);
  const col = Object.fromEntries(fields(header).map((name, i) => [name, i]));
  const best = new Map();
  let unplaced = 0;
  for (const line of lines) {
    const f = fields(line);
    const iata = f[col.iata_code];
    const type = f[col.type];
    if (!/^[A-Z]{3}$/.test(iata || '') || !TYPES.has(type) || f[col.scheduled_service] !== 'yes') continue;
    const latitude = Number(f[col.latitude_deg]);
    const longitude = Number(f[col.longitude_deg]);
    if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) continue;
    const found = countryAtPosition(latitude, longitude);
    const iso = f[col.iso_country];
    const place = found ?? (KNOWN.has(iso) ? iso : null);
    if (!place) {
      unplaced++;
      continue;
    }
    const nation = place === 'GB' ? ukNationAt(latitude, longitude) : null;
    const row = [tidy(f[col.name]), tidy(f[col.municipality] || ''), place, round(latitude), round(longitude), nation];
    const kept = best.get(iata);
    if (!kept || RANK[type] > kept.rank) best.set(iata, { rank: RANK[type], row });
  }
  const sorted = Object.fromEntries([...best.keys()].sort().map((code) => [code, best.get(code).row]));
  return { airports: sorted, unplaced };
}

const [csvPath, flag] = process.argv.slice(2);
if (!csvPath) {
  console.error('Usage: node images/src/tools/airports.mjs <airports.csv> [--check]');
  process.exit(1);
}
const { airports, unplaced } = build(csvPath);
const serverText = `${JSON.stringify(airports)}\n`;
const clientText =
  `// GENERATED by images/src/tools/airports.mjs from OurAirports (public domain): don't edit by hand.\n` +
  `// IATA code -> [name, city, place on the map, latitude, longitude, UK nation or null]. The\n` +
  `// server's copy is server/src/data/airports.json. Loaded only by the flight log.\n` +
  `export const AIRPORT_DATA = ${JSON.stringify(airports)};\n`;

if (flag === '--check') {
  const same = fs.existsSync(SERVER_OUT) && fs.readFileSync(SERVER_OUT, 'utf8') === serverText && fs.existsSync(CLIENT_OUT) && fs.readFileSync(CLIENT_OUT, 'utf8') === clientText;
  console.log(same ? 'Airports up to date.' : 'Airports differ: run the tool again.');
  process.exit(same ? 0 : 1);
}
fs.mkdirSync(path.dirname(CLIENT_OUT), { recursive: true });
fs.writeFileSync(SERVER_OUT, serverText);
fs.writeFileSync(CLIENT_OUT, clientText);
console.log(`${Object.keys(airports).length} airports written (${unplaced} with no place on the map left out).`);
