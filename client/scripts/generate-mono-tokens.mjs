// Black and white (the map style `mono`, a switch until 19 Nov 2026): writes, into src/styles/index.css
// between the "mono-tokens" markers, a :root[data-mono] block that gives every colour token
// of the :root block the grey a greyscale filter makes of it (its luminance:
// 0.2126 R + 0.7152 G + 0.0722 B), alpha kept, except the countries' (CHOSEN, below). The map page sets data-mono on <html> while
// the setting is on, so containers outside its greyscale filter (the photo viewer's and the
// slideshow's frames, dialogs drawn in portals) turn grey too, while photos keep their colour.
//
// Run from client/ whenever a colour token in :root changes:
//   node scripts/generate-mono-tokens.mjs          (writes the block)
//   node scripts/generate-mono-tokens.mjs --check  (fails if it's out of date)
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const cssPath = resolve(dirname(fileURLToPath(import.meta.url)), '../src/styles/index.css');
const START = '/* mono-tokens:start */';
const END = '/* mono-tokens:end */';
const check = process.argv.includes('--check');

const css = await readFile(cssPath, 'utf8');
const rootStart = css.indexOf(':root {');
const rootEnd = css.indexOf('\n}', rootStart);
if (rootStart < 0 || rootEnd < 0) throw new Error('No :root block in index.css');
const root = css.slice(rootStart + ':root {'.length, rootEnd).replace(/\/\*[\s\S]*?\*\//g, '');

const grey = (r, g, b) => Math.round(0.2126 * r + 0.7152 * g + 0.0722 * b);

// Chosen rather than computed. By brightness alone every accent (the poster red, the
// browns, the sea) came out a mid grey and nothing was black, so:
//   - ink, edges, rules and buttons are black, the paper white (light-dark: the dark
//     theme the other way round);
//   - the sea is charcoal (its depths show as greys over it) and the borders black;
//   - the land is near white and the seven pastels seven distinct greys (by brightness
//     the yellow and pale green came out as white as land not visited yet; touching
//     countries never share a pastel, so they never share a grey either).
const CHOSEN = {
  '--colour6': 'light-dark(#000000, #ffffff)',
  '--colour7': 'light-dark(#3a3a3a, #c8c8c8)',
  '--colour8': 'light-dark(#e4e4e4, #2e2e2e)',
  '--colour9': 'light-dark(#2b2b2b, #d0d0d0)',
  '--poster-red': '#000000',
  '--poster-red-ink': '#ffffff',
  '--poster-red-deep': '#000000',
  '--poster-red-strong': '#000000',
  '--danger-red': '#000000',
  '--danger-ink': '#ffffff',
  '--poster-brown': '#000000',
  '--poster-paper': '#e4e4e4',
  '--paper-cream': 'light-dark(#ffffff, #111111)',
  '--map-sea': '#262626',
  '--map-sea-mid': '#1a1a1a',
  '--map-sea-deep': '#0d0d0d',
  '--map-land-edge': '#000000',
  '--map-ice': '#ffffff',
  '--map-ice-edge': '#000000',
  '--map-land': '#f7f7f7',
  '--map-visit-1': '#dcdcdc',
  '--map-visit-2': '#cdcdcd',
  '--map-visit-3': '#bebebe',
  '--map-visit-4': '#afafaf',
  '--map-visit-5': '#a0a0a0',
  '--map-visit-6': '#919191',
  '--map-visit-7': '#c6c6c6',
  // The planned strings a lighter grey than the visited ones' (by brightness they came out
  // almost the same: 25 Nov 2026), so the two kinds still tell apart
  '--map-plan-string': '#8c8c8c',
  // The places been to, filled by a design: a dark grey, plain against the near-white land
  '--map-visited': '#3c3c3c',
};
const hex2 = (n) => n.toString(16).padStart(2, '0');

// Every colour literal in a value, made grey
function greyed(value) {
  return value
    .replace(/#([0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3})\b/gi, (_, h) => {
      const full = h.length === 3 ? [...h].map((c) => c + c).join('') : h;
      const [r, g, b] = [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16));
      const level = hex2(grey(r, g, b));
      return `#${level}${level}${level}${full.length === 8 ? full.slice(6) : ''}`;
    })
    .replace(/rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)/gi, (match, r, g, b) => {
      const level = grey(Number(r), Number(g), Number(b));
      const separator = match.includes(',') ? ', ' : ' ';
      return `${match.slice(0, match.indexOf('(') + 1)}${level}${separator}${level}${separator}${level}`;
    });
}

const lines = [];
for (const declaration of root.split(';')) {
  const match = declaration.match(/^\s*(--[a-z0-9-]+)\s*:\s*([\s\S]+?)\s*$/i);
  if (!match) continue;
  const [, name, value] = match;
  if (!CHOSEN[name] && !/#[0-9a-f]{3,8}\b|rgba?\(/i.test(value)) continue;
  lines.push(`  ${name}: ${CHOSEN[name] || greyed(value.replace(/\s*\n\s*/g, ' '))};`);
}

// In the file's own line endings (it may be checked out with Windows ones)
const eol = css.includes('\r\n') ? '\r\n' : '\n';
const block = `${START}
/* Black and white: every colour token above as the grey a greyscale filter makes of it.
   GENERATED by scripts/generate-mono-tokens.mjs from the :root block; don't edit by hand. */
:root[data-mono] {
${lines.join('\n')}
}
${END}`.replace(/\r?\n/g, eol);

const at = css.indexOf(START);
const end = css.indexOf(END);
if (at < 0 || end < 0) throw new Error(`Add the ${START} and ${END} markers to index.css first`);
const next = css.slice(0, at) + block + css.slice(end + END.length);
if (check) {
  if (next !== css) {
    console.error('index.css: the black and white tokens are out of date. Run node scripts/generate-mono-tokens.mjs');
    process.exit(1);
  }
  console.log('Black and white tokens up to date.');
} else {
  await writeFile(cssPath, next);
  console.log(`Wrote ${lines.length} grey tokens to index.css`);
}
