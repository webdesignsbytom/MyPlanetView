// Copies the demo couple's travels (server/prisma/seed/data/demoTravels.js, the history the
// server's seed writes on the USER's map) into mock mode, so the mock's test user's map has the
// same countries, trips, moments, ticks, flights and strings (src/dev/mock/seed.js). The flights'
// distances and the strings are worked out by the server's file; this writes their values.
//
// Run from client/ whenever the server's file changes:
//   node scripts/generate-mock-travels.mjs          (writes the file)
//   node scripts/generate-mock-travels.mjs --check  (fails if it's out of date)
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, '../server/prisma/seed/data/demoTravels.js');
const target = resolve(root, 'src/dev/mock/data/demoTravels.js');

const demo = await import(pathToFileURL(source).href);
const NAMES = ['DEMO_TRAVELLERS', 'DEMO_VISITS', 'DEMO_TRIPS', 'DEMO_MOMENTS', 'DEMO_LANDMARK_TICKS', 'DEMO_FLIGHTS', 'DEMO_ONE_SHOTS', 'DEMO_STATES', 'DEMO_STRINGS'];
const output = `// GENERATED by scripts/generate-mock-travels.mjs from server/prisma/seed/data/demoTravels.js
// (the demo couple's travels, which the server's seed writes too). Don't edit it here: change the
// server's file, then run \`node scripts/generate-mock-travels.mjs\` in client/. Mock mode only:
// the test user's map in src/dev/mock/seed.js is built from it. ${demo.DEMO_VISITS.length} places, ${demo.DEMO_TRIPS.length} trips, ${demo.DEMO_MOMENTS.length} moments.

${NAMES.map((name) => `export const ${name} = ${JSON.stringify(demo[name], null, 2)};`).join('\n\n')}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? await readFile(target, 'utf8') : '';
  if (current !== output) {
    console.error('❌ src/dev/mock/data/demoTravels.js is out of date: run node scripts/generate-mock-travels.mjs');
    process.exit(1);
  }
  console.log('✅ The mock demo travels are up to date');
} else {
  await writeFile(target, output, 'utf8');
  console.log(`✅ Wrote the demo travels to src/dev/mock/data/demoTravels.js`);
}
