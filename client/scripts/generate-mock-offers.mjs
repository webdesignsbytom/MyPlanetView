// Copies the server's example travel offers (server/prisma/seed/data/offers.example.json,
// the file the server's seed imports) into mock mode, so the mock's ad cards, Travel Desk
// and admin offers page show the same offers. The mock gives each a fixed id (by its place
// in the file) and dates.
//
// Run from client/ whenever the server's file changes:
//   node scripts/generate-mock-offers.mjs          (writes the file)
//   node scripts/generate-mock-offers.mjs --check  (fails if it's out of date)
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, '../server/prisma/seed/data/offers.example.json');
const target = resolve(root, 'src/dev/mock/data/offers.js');

const { offers } = JSON.parse(await readFile(source, 'utf8'));
const output = `// GENERATED by scripts/generate-mock-offers.mjs from server/prisma/seed/data/offers.example.json
// (the example offers the server's seed imports). Don't edit it here: change the server's
// file, then run \`node scripts/generate-mock-offers.mjs\` in client/. Mock mode only: the mock
// store's \`offers\` start from it (src/dev/mock/seed.js). ${offers.length} offers, all fictional.

export const EXAMPLE_OFFERS = ${JSON.stringify(offers, null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? await readFile(target, 'utf8') : '';
  if (current !== output) {
    console.error('❌ src/dev/mock/data/offers.js is out of date: run node scripts/generate-mock-offers.mjs');
    process.exit(1);
  }
  console.log('✅ Mock offers are up to date');
} else {
  await writeFile(target, output, 'utf8');
  console.log(`✅ Wrote ${offers.length} example offers to src/dev/mock/data/offers.js`);
}
