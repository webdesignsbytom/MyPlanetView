// Copies the server's landmark seed data into mock mode (src/dev/mock/), so the mock API
// answers GET /api/landmarks with the same 1,366 landmarks as the server:
// server/prisma/seed/data/landmarks.js (the 177) and landmarksUnesco.js (the UNESCO World
// Heritage Sites), combined as server/prisma/seed/landmarks.js landmarkRows() does it:
// `isUnesco` is true for every UNESCO site, and for the 177 in UNESCO_IN_EXISTING.
// The mock adds each one's id, slug and map pin (src/dev/mock/views.js).
//
// Run from client/ whenever either server file changes:
//   node scripts/generate-mock-landmarks.mjs          (writes the file)
//   node scripts/generate-mock-landmarks.mjs --check  (fails if it's out of date)
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const data = resolve(root, '../server/prisma/seed/data');
const target = resolve(root, 'src/dev/mock/data/landmarks.js');

const { LANDMARKS } = await import(pathToFileURL(resolve(data, 'landmarks.js')).href);
const { UNESCO_IN_EXISTING, UNESCO_LANDMARKS } = await import(pathToFileURL(resolve(data, 'landmarksUnesco.js')).href);

const unescoInExisting = new Set(UNESCO_IN_EXISTING);
const rows = [
  ...LANDMARKS.map((landmark) => ({ ...landmark, isUnesco: unescoInExisting.has(landmark.wikidataId) })),
  ...UNESCO_LANDMARKS.map((landmark) => ({ ...landmark, isUnesco: true })),
];

// What the API gives (less what the mock works out), one landmark a line
const line = ({ countryCode, name, latitude, longitude, matchRadiusM, isUnesco }) =>
  `  { countryCode: ${JSON.stringify(countryCode)}, name: ${JSON.stringify(name)}, latitude: ${latitude}, longitude: ${longitude}, matchRadiusM: ${matchRadiusM}, isUnesco: ${isUnesco} },`;

const unesco = rows.filter((row) => row.isUnesco).length;
const output = `// GENERATED by scripts/generate-mock-landmarks.mjs from server/prisma/seed/data/landmarks.js
// (${LANDMARKS.length}) and landmarksUnesco.js (${UNESCO_LANDMARKS.length}), combined as the server's seed combines them
// (server/prisma/seed/landmarks.js). Don't edit it here: change the server's files, then run
// \`node scripts/generate-mock-landmarks.mjs\` in client/. Mock mode only (npm run dev:mock): the mock
// API answers GET /api/landmarks from it (src/dev/mock/views.js adds ids, slugs and pins).
// ${rows.length} landmarks, ${unesco} of them UNESCO World Heritage Sites. Never imported outside src/dev/mock.

export const LANDMARKS = [
${rows.map(line).join('\n')}
];
`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? await readFile(target, 'utf8') : '';
  if (current !== output) {
    console.error('❌ src/dev/mock/data/landmarks.js is out of date: run node scripts/generate-mock-landmarks.mjs');
    process.exit(1);
  }
  console.log('✅ Mock landmarks are up to date');
} else {
  await writeFile(target, output, 'utf8');
  console.log(`✅ Wrote ${rows.length} landmarks (${unesco} UNESCO) to src/dev/mock/data/landmarks.js`);
}
