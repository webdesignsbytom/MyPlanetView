// Copies the landmarks the country pages show into the client build:
// server/prisma/seed/data/landmarks.js (the 177 well-known ones) and landmarksUnesco.js
// (the UNESCO World Heritage Sites) -> src/content/countries/landmarks.generated.js,
// grouped by country code, with each one's photo (src/utils/map/landmarkPhotos.js, made by
// images/src/tools/landmark-photos.mjs). A pre-rendered page can't call the API, so the
// pages read this copy instead.
//
// A country's list: its well-known landmarks (by name), then its World Heritage Sites,
// the earliest inscribed first (the classics: UNESCO's id numbers, in the comment on each
// line of landmarksUnesco.js), MAX_PER_COUNTRY at most.
//
// Run from client/ whenever the landmark files or the landmark photos change:
//   node scripts/generate-country-landmarks.mjs          (writes the file)
//   node scripts/generate-country-landmarks.mjs --check  (fails if it's out of date)
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const seedData = resolve(root, '../server/prisma/seed/data');
const target = resolve(root, 'src/content/countries/landmarks.generated.js');

export const MAX_PER_COUNTRY = 9;

// Only what a page shows (the match radius is in the landmark's line)
const FIELDS = ['name', 'category', 'matchRadiusM', 'wikidataId'];

const { LANDMARKS } = await import(pathToFileURL(resolve(seedData, 'landmarks.js')).href);
const { UNESCO_LANDMARKS } = await import(pathToFileURL(resolve(seedData, 'landmarksUnesco.js')).href);
const { slugify } = await import(pathToFileURL(resolve(root, '../server/src/utils/slug.js')).href);
const { LANDMARK_PHOTOS, LICENCES } = await import(pathToFileURL(resolve(root, 'src/utils/map/landmarkPhotos.js')).href);

// UNESCO's id number for each site, from the comment on its line ("// WHS 208, 2003")
const unescoText = await readFile(resolve(seedData, 'landmarksUnesco.js'), 'utf8');
const whsNumber = new Map(
  [...unescoText.matchAll(/wikidataId: '(Q\d+)'[^\n]*\/\/ WHS (\d+)/g)].map(([, id, number]) => [id, Number(number)])
);

const byCode = {};
const add = (landmark, isUnesco) => {
  const slug = slugify(landmark.name);
  (byCode[landmark.countryCode] ||= []).push({
    ...Object.fromEntries(FIELDS.map((field) => [field, landmark[field]])),
    slug,
    isUnesco,
    whs: whsNumber.get(landmark.wikidataId) ?? Infinity,
  });
};
LANDMARKS.forEach((landmark) => add(landmark, false));
UNESCO_LANDMARKS.forEach((landmark) => add(landmark, true));

const codes = Object.keys(byCode).sort();
const shown = [];
const lines = codes.map((code) => {
  const items = byCode[code]
    .slice()
    .sort((a, b) => Number(a.isUnesco) - Number(b.isUnesco) || (a.isUnesco ? a.whs - b.whs : a.name.localeCompare(b.name)))
    .slice(0, MAX_PER_COUNTRY)
    .map(({ whs: _whs, isUnesco: _isUnesco, ...item }) => {
      shown.push(item.slug);
      return JSON.stringify(item);
    });
  return `  ${code}: [${items.join(', ')}],`;
});

// The photos of the landmarks shown, in landmarkPhotos.js's own form (landmarkPhotoInfo reads it)
const photoLines = shown
  .filter((slug) => LANDMARK_PHOTOS[slug])
  .sort()
  .map((slug) => `  ${JSON.stringify(slug)}: ${JSON.stringify(LANDMARK_PHOTOS[slug])},`);

const output = `// GENERATED by scripts/generate-country-landmarks.mjs from server/prisma/seed/data/landmarks.js
// and landmarksUnesco.js (the Landmark table's seed data) and src/utils/map/landmarkPhotos.js.
// Don't edit it here: change those, then run \`node scripts/generate-country-landmarks.mjs\` in
// client/. The country pages show these, since a pre-rendered page can't ask the API: each
// country's well-known landmarks, then its World Heritage Sites (earliest inscribed first),
// ${MAX_PER_COUNTRY} at most. ${shown.length} landmarks in ${codes.length} countries.
export const COUNTRY_LANDMARKS = {
${lines.join('\n')}
};

// Their photos (credits as landmarkPhotos.js: [width, height, author, licence, Commons file])
export const LICENCES = ${JSON.stringify(LICENCES)};
export const LANDMARK_PHOTOS = {
${photoLines.join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? await readFile(target, 'utf8') : '';
  if (current !== output) {
    console.error('❌ src/content/countries/landmarks.generated.js is out of date: run node scripts/generate-country-landmarks.mjs');
    process.exit(1);
  }
  console.log('✅ Country landmarks are up to date');
} else {
  await writeFile(target, output, 'utf8');
  console.log(`✅ Wrote ${shown.length} landmarks (${photoLines.length} with photos) for ${codes.length} countries to src/content/countries/landmarks.generated.js`);
}
