// Copies the landmarks the country pages show into the client build:
// server/prisma/seed/data/landmarks.js (the Landmark table's data) ->
// src/content/countries/landmarks.generated.js, grouped by country code.
// A pre-rendered page can't call the API, so the pages read this copy instead.
//
// Run from client/ whenever the server's landmark file changes:
//   node scripts/generate-country-landmarks.mjs          (writes the file)
//   node scripts/generate-country-landmarks.mjs --check  (fails if it's out of date)
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, '../server/prisma/seed/data/landmarks.js');
const target = resolve(root, 'src/content/countries/landmarks.generated.js');

// Only what a page shows (the match radius is in the landmark's line)
const FIELDS = ['name', 'category', 'matchRadiusM', 'wikidataId'];

const { LANDMARKS } = await import(pathToFileURL(source).href);

const byCode = {};
for (const landmark of LANDMARKS) {
  (byCode[landmark.countryCode] ||= []).push(Object.fromEntries(FIELDS.map((field) => [field, landmark[field]])));
}
const codes = Object.keys(byCode).sort();

const lines = codes.map((code) => {
  const items = byCode[code]
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((item) => JSON.stringify(item));
  return `  ${code}: [${items.join(', ')}],`;
});

const output = `// GENERATED by scripts/generate-country-landmarks.mjs from server/prisma/seed/data/landmarks.js
// (the Landmark table's seed data). Don't edit it here: change the server's file, then run
// \`node scripts/generate-country-landmarks.mjs\` in client/. The country pages show these,
// since a pre-rendered page can't ask the API. ${LANDMARKS.length} landmarks in ${codes.length} countries.
export const COUNTRY_LANDMARKS = {
${lines.join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? await readFile(target, 'utf8') : '';
  if (current !== output) {
    console.error('❌ src/content/countries/landmarks.generated.js is out of date: run node scripts/generate-country-landmarks.mjs');
    process.exit(1);
  }
  console.log('✅ Country landmarks are up to date');
} else {
  await writeFile(target, output, 'utf8');
  console.log(`✅ Wrote ${LANDMARKS.length} landmarks for ${codes.length} countries to src/content/countries/landmarks.generated.js`);
}
