// Writes src/utils/map/countryStyle.js from the map's own shapes:
//   COUNTRY_COLOUR: one of the old map's seven pastels per country (1–7), chosen so
//     countries that touch never share a colour (greedy graph colouring). Special places
//     (kind 'SPECIAL': Antarctica, drawn as ice, and the poles, drawn as markers) get none;
//   COUNTRY_LABEL_WIDTH: the width of each shape's largest part (countries and
//     Antarctica), in map units, so a name is only drawn once it fits.
// Run after the shapes change: node scripts/generate-country-style.mjs
import fs from 'node:fs';
import { COUNTRY_SHAPES } from '../src/utils/map/countryShapes.js';
import { COUNTRIES } from '../src/utils/map/countries.js';

const COLOURS = 7;
const CELL = 0.8; // vertices of two countries within about one cell are "touching"
const MICRO_REACH = 8; // a micro-state (a dot) touches whatever shape is this close
// Only the countries are coloured
const COLOURED = COUNTRIES.filter((c) => c.kind !== 'SPECIAL');
const colouredCodes = new Set(COLOURED.map((c) => c.code));

function parsePath(d) {
  const t = d.match(/[a-zA-Z]|-?\d*\.?\d+(?:e-?\d+)?/g) || [];
  const polys = [];
  let poly = null, x = 0, y = 0, cmd = null, i = 0, sx = 0, sy = 0;
  const n = () => parseFloat(t[i++]);
  while (i < t.length) {
    if (/[a-zA-Z]/.test(t[i])) cmd = t[i++];
    switch (cmd) {
      case 'M': x = n(); y = n(); poly = [[x, y]]; polys.push(poly); sx = x; sy = y; cmd = 'L'; break;
      case 'm': x += n(); y += n(); poly = [[x, y]]; polys.push(poly); sx = x; sy = y; cmd = 'l'; break;
      case 'L': x = n(); y = n(); poly.push([x, y]); break;
      case 'l': x += n(); y += n(); poly.push([x, y]); break;
      case 'H': x = n(); poly.push([x, y]); break;
      case 'h': x += n(); poly.push([x, y]); break;
      case 'V': y = n(); poly.push([x, y]); break;
      case 'v': y += n(); poly.push([x, y]); break;
      case 'Z': case 'z': x = sx; y = sy; break;
      default: throw new Error(`Unsupported path command ${cmd}`);
    }
  }
  return polys;
}

const area = (p) => Math.abs(p.reduce((s, [x1, y1], k) => { const [x2, y2] = p[(k + 1) % p.length]; return s + x1 * y2 - x2 * y1; }, 0) / 2);

// Polygons per country, plus the largest shape's width
const polysByCode = {};
const labelWidth = {};
for (const [code, paths] of Object.entries(COUNTRY_SHAPES)) {
  const polys = paths.flatMap(parsePath).filter((p) => p.length >= 3);
  polysByCode[code] = polys;
  const main = polys.reduce((a, b) => (area(b) > area(a) ? b : a));
  const xs = main.map(([px]) => px);
  labelWidth[code] = Math.round((Math.max(...xs) - Math.min(...xs)) * 10) / 10;
}

// Spatial hash of every country's vertices → the countries with a vertex in that cell
const cells = new Map();
const key = (cx, cy) => `${cx},${cy}`;
const countryPolys = Object.entries(polysByCode).filter(([code]) => colouredCodes.has(code));
for (const [code, polys] of countryPolys) {
  for (const p of polys) for (const [px, py] of p) {
    const k = key(Math.floor(px / CELL), Math.floor(py / CELL));
    if (!cells.has(k)) cells.set(k, new Set());
    cells.get(k).add(code);
  }
}
const neighbours = Object.fromEntries(COLOURED.map((c) => [c.code, new Set()]));
for (const [k, codes] of cells) {
  const [cx, cy] = k.split(',').map(Number);
  for (let dx = -1; dx <= 1; dx++) for (let dy = -1; dy <= 1; dy++) {
    const other = cells.get(key(cx + dx, cy + dy));
    if (!other) continue;
    for (const a of codes) for (const b of other) if (a !== b) { neighbours[a].add(b); neighbours[b].add(a); }
  }
}
// Micro-states: a dot at the pin touches any shape nearby
for (const c of COLOURED.filter((x) => !COUNTRY_SHAPES[x.code])) {
  for (const [code, polys] of countryPolys) {
    if (polys.some((p) => p.some(([px, py]) => Math.hypot(px - c.pinX, py - c.pinY) < MICRO_REACH))) {
      neighbours[c.code].add(code); neighbours[code].add(c.code);
    }
  }
}

// Greedy colouring, most-connected first; ties go to the least-used colour
const order = COLOURED.map((c) => c.code).sort((a, b) => neighbours[b].size - neighbours[a].size || a.localeCompare(b));
const colour = {};
const used = Array(COLOURS + 1).fill(0);
for (const code of order) {
  const taken = new Set([...neighbours[code]].map((n) => colour[n]).filter(Boolean));
  const free = [];
  for (let c = 1; c <= COLOURS; c++) if (!taken.has(c)) free.push(c);
  if (!free.length) throw new Error(`No free colour for ${code}`);
  free.sort((a, b) => used[a] - used[b] || a - b);
  colour[code] = free[0];
  used[free[0]]++;
}
const clashes = Object.entries(neighbours).flatMap(([a, ns]) => [...ns].filter((b) => colour[a] === colour[b]).map((b) => `${a}-${b}`));
if (clashes.length) throw new Error(`Neighbours share a colour: ${clashes.join(', ')}`);

const codes = COUNTRIES.map((c) => c.code).sort();
const line = (obj) => codes.filter((c) => obj[c] !== undefined).map((c) => `${c}: ${obj[c]}`).join(', ');
const file = `// Generated by scripts/generate-country-style.mjs from the map's shapes. Don't edit by
// hand; re-run the script if countryShapes.js changes.

// One of the old map's seven pastels per country (--map-visit-1 … 7); countries that
// touch never share a colour.
export const COUNTRY_COLOUR = { ${line(colour)} };

// Width of each country's largest shape in map units (none for the micro-states and
// the poles), so a name is only drawn once it fits.
export const COUNTRY_LABEL_WIDTH = { ${line(labelWidth)} };
`;
fs.writeFileSync(new URL('../src/utils/map/countryStyle.js', import.meta.url), file);
const degree = Object.values(neighbours).map((s) => s.size);
console.log(`countries: ${COLOURED.length}, colours used: ${used.slice(1).join('/')}, max neighbours: ${Math.max(...degree)}, isolated: ${degree.filter((d) => d === 0).length}`);
