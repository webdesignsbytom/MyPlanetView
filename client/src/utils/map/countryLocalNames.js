// Case aside, the same name: "eSwatini" is Eswatini; "México" isn't Mexico
const sameName = (a, b) => a.localeCompare(b, undefined, { sensitivity: 'accent' }) === 0;

/**
 * The local names to show beside a country's English name: `{ lang, name }` for each that
 * differs from it (none for Portugal; 日本 for Japan; four for Switzerland).
 */
export function localNamesBeside(code, englishName) {
  return (LOCAL_NAMES[code] || []).filter(([, name]) => !sameName(name, englishName)).map(([lang, name]) => ({ lang, name }));
}
